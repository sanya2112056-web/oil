def build_user_payload(item: NewsItem, snapshot: dict,
                       unavailable: list[str], importance_score: int) -> str:
    price = best_wti_price(snapshot)
    lines = [
        "=== НОВИНА ===",
        f"Заголовок: {item.title}",
        f"Джерело: {item.source}",
        f"Опис: {item.summary or '(немає)'}",
        f"URL: {item.url}",
        f"Оцінка важливості (евристика бота): {importance_score}/10",
        "",
        "=== ЗНІМОК РИНКУ (доступні показники) ===",
    ]
    if price is not None:
        lines.append(f"Поточна ціна WTI (найкраще доступне): ~${price}")
    if snapshot:
        for k, v in snapshot.items():
            lines.append(f"{k}: {v}")
    else:
        lines.append("(ринкові показники недоступні — ключі API не додані)")
    if unavailable:
        lines.append("")
        lines.append("Недоступні джерела даних (немає ключа/помилка): "
                     + ", ".join(unavailable))
    lines.append("")
    lines.append("Проаналізуй і поверни JSON у заданому форматі.")
    return "\n".join(lines)


async def analyze_news(item: NewsItem, snapshot: dict,
                       unavailable: list[str], importance_score: int) -> dict:
    payload = build_user_payload(item, snapshot, unavailable, importance_score)
    result = await claude_client.analyze(SYSTEM_PROMPT, payload)
    # підстрахуємо обов'язкові поля
    result.setdefault("signal", "NEUTRAL")
    result.setdefault("probability", 0)
    return result


